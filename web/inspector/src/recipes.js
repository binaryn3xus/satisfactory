export function getSchematicManager(save) {
    if (!save || !save.levels) return null;
    for (const lvl in save.levels) {
        for (const obj of save.levels[lvl].objects) {
            if (obj.typePath && obj.typePath.includes("SchematicManager")) {
                return obj;
            }
        }
    }
    return null;
}

