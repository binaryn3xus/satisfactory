export function isAlternateUnlocked(save, alt) {
    const sm = getSchematicManager(save);
    const rm = getRecipeManager(save);
    const purchased = sm?.properties?.mPurchasedSchematics?.values || [];
    if (purchased.some(p => p.pathName === alt.schematicPath || (alt.id && p.pathName && p.pathName.includes(alt.id)))) {
        return true;
    }
    if (alt.recipePath) {
        const recipes = rm?.properties?.mAvailableRecipes?.values || [];
        const baseRec = alt.recipePath.split(".").pop();
        if (recipes.some(r => r.pathName === alt.recipePath || (baseRec && r.pathName && r.pathName.includes(baseRec)))) {
            return true;
        }
    }
    return false;
}

export function unlockAlternate(save, alt) {
    const sm = getSchematicManager(save);
    const rm = getRecipeManager(save);
    let changed = false;

    if (sm) {
        if (!sm.properties) sm.properties = {};
        if (!sm.properties.mPurchasedSchematics) {
            sm.properties.mPurchasedSchematics = {
                type: "ArrayProperty",
                name: "mPurchasedSchematics",
                propertyTagType: { name: "ArrayProperty", children: [{ name: "ObjectProperty", children: [] }] },
                values: []
            };
        }
        const vals = sm.properties.mPurchasedSchematics.values;
        if (!vals.some(v => v.pathName === alt.schematicPath || (alt.id && v.pathName.includes(alt.id)))) {
            vals.push({ levelName: "", pathName: alt.schematicPath });
            changed = true;
        }
    }

    if (rm && alt.recipePath) {
        if (!rm.properties) rm.properties = {};
        if (!rm.properties.mAvailableRecipes) {
            rm.properties.mAvailableRecipes = {
                type: "ArrayProperty",
                name: "mAvailableRecipes",
                propertyTagType: { name: "ArrayProperty", children: [{ name: "ObjectProperty", children: [] }] },
                values: []
            };
        }
        const rVals = rm.properties.mAvailableRecipes.values;
        const baseRec = alt.recipePath.split(".").pop();
        if (!rVals.some(v => v.pathName === alt.recipePath || (baseRec && v.pathName.includes(baseRec)))) {
            rVals.push({ levelName: "", pathName: alt.recipePath });
            changed = true;
        }
    }

    return changed;
}

export function lockAlternate(save, alt) {
    const sm = getSchematicManager(save);
    const rm = getRecipeManager(save);
    let changed = false;

    if (sm?.properties?.mPurchasedSchematics?.values) {
        const origLen = sm.properties.mPurchasedSchematics.values.length;
        sm.properties.mPurchasedSchematics.values = sm.properties.mPurchasedSchematics.values.filter(
            v => v.pathName !== alt.schematicPath && (!alt.id || !v.pathName.includes(alt.id))
        );
        if (sm.properties.mPurchasedSchematics.values.length !== origLen) changed = true;
    }

    if (rm?.properties?.mAvailableRecipes?.values && alt.recipePath) {
        const baseRec = alt.recipePath.split(".").pop();
        const origLen = rm.properties.mAvailableRecipes.values.length;
        rm.properties.mAvailableRecipes.values = rm.properties.mAvailableRecipes.values.filter(
            v => v.pathName !== alt.recipePath && (!baseRec || !v.pathName.includes(baseRec))
        );
        if (rm.properties.mAvailableRecipes.values.length !== origLen) changed = true;
    }

    return changed;
}

export function unlockAllAlternates(save) {
    let count = 0;
    for (const alt of ALTERNATE_RECIPES) {
        if (!isAlternateUnlocked(save, alt)) {
            if (unlockAlternate(save, alt)) count++;
        }
    }
    return count;
}

export function lockAllAlternates(save) {
    let count = 0;
    for (const alt of ALTERNATE_RECIPES) {
        if (isAlternateUnlocked(save, alt)) {
            if (lockAlternate(save, alt)) count++;
        }
    }
    return count;
}

export function isMAMTreeUnlocked(save, tree) {
    const resM = getResearchManager(save);
    const unlockedTrees = resM?.properties?.mUnlockedResearchTrees?.values || [];
    return unlockedTrees.some(t => t.pathName === tree.treePath);
}

export function isMAMNodeUnlocked(save, node) {
    const sm = getSchematicManager(save);
    const purchased = sm?.properties?.mPurchasedSchematics?.values || [];
    return purchased.some(p => p.pathName === node.schematicPath || (node.id && p.pathName.includes(node.id)));
}

export function unlockMAMTree(save, tree) {
    const sm = getSchematicManager(save);
    const resM = getResearchManager(save);
    let count = 0;

    if (resM) {
        if (!resM.properties) resM.properties = {};
        if (!resM.properties.mUnlockedResearchTrees) {
            resM.properties.mUnlockedResearchTrees = {
                type: "ArrayProperty",
                name: "mUnlockedResearchTrees",
                propertyTagType: { name: "ArrayProperty", children: [{ name: "ObjectProperty", children: [] }] },
                values: []
            };
        }
        const trees = resM.properties.mUnlockedResearchTrees.values;
        if (!trees.some(t => t.pathName === tree.treePath)) {
            trees.push({ levelName: "", pathName: tree.treePath });
        }
    }

    if (sm) {
        if (!sm.properties) sm.properties = {};
        if (!sm.properties.mPurchasedSchematics) {
            sm.properties.mPurchasedSchematics = {
                type: "ArrayProperty",
                name: "mPurchasedSchematics",
                propertyTagType: { name: "ArrayProperty", children: [{ name: "ObjectProperty", children: [] }] },
                values: []
            };
        }
        const vals = sm.properties.mPurchasedSchematics.values;
        for (const n of tree.nodes) {
            if (!vals.some(v => v.pathName === n.schematicPath || (n.id && v.pathName.includes(n.id)))) {
                vals.push({ levelName: "", pathName: n.schematicPath });
                count++;
            }
        }
    }

    return count;
}

export function unlockAllMAMTrees(save) {
    let total = 0;
    for (const tree of MAM_TREES) {
        total += unlockMAMTree(save, tree);
    }
    return total;
}
