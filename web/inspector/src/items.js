/**
 * Filter out non-item descriptors such as cosmetic skins, building materials, swatches, and rule cards.
 */
export function isPhysicalItemDescriptor(path) {
    if (!path || typeof path !== 'string') return false;
    if (!path.startsWith('/') || path.startsWith('/Script/')) return false;
    if (path.includes('SwatchDesc_') || path.includes('MaterialDesc_') || path.includes('Desc_Skin_') ||
        path.includes('Desc_Helmet_') || path.includes('Desc_Wildcard') || path.includes('Desc_Overflow') ||
        path.includes('Desc_None') || path.includes('Recipe_') || path.includes('Build_')) {
        return false;
    }
    return path.includes('Desc_') || path.includes('Descriptor') || path.includes('/Items/') || path.includes('ItemDesc_');
}

/**
 * Dynamically scan a parsed save AST for all item descriptors present anywhere in the world.
 */
export function scanSaveForItemDescriptors(save) {
    const discoveredPaths = new Set();
    if (!save || !save.levels) return [];

    const extract = (val) => {
        if (!val) return;
        if (typeof val === 'string') {
            if (isPhysicalItemDescriptor(val)) discoveredPaths.add(val);
        } else if (Array.isArray(val)) {
            for (const el of val) extract(el);
        } else if (typeof val === 'object') {
            if (val.itemReference?.pathName && isPhysicalItemDescriptor(val.itemReference.pathName)) {
                discoveredPaths.add(val.itemReference.pathName);
            }
            for (const k in val) {
                extract(val[k]);
            }
        }
    };

    for (const lvl in save.levels) {
        for (const obj of save.levels[lvl].objects) {
            if (obj.properties) extract(obj.properties);
        }
    }

    const moddedOrDynamicItems = [];
    for (const p of discoveredPaths) {
        if (!BASE_ITEM_MAP.has(p)) {
            const isMod = !p.startsWith('/Game/FactoryGame/');
            const name = friendlyItemName(p);
            const isEquip = p.includes('Equipment') || p.includes('Spear') || p.includes('Shank') || p.includes('Gun');
            moddedOrDynamicItems.push({
                path: p,
                name: isMod ? `[Mod] ${name}` : name,
                category: isMod ? 'Modded & Custom World Items' : 'Other World Items',
                defaultQty: isEquip ? 1 : 50,
                icon: isMod ? '🧩' : '📦'
            });
        }
    }

    return moddedOrDynamicItems;
}

/**
 * Returns complete combined catalog (standard 1.2 items + save-scanned items), sorted and grouped.
 */
export function getAllAvailableItems(save) {
    const all = [...BASE_ITEM_CATALOG];
    const scanned = scanSaveForItemDescriptors(save);
    all.push(...scanned);

    return all.sort((a, b) => {
        if (a.category !== b.category) {
            return a.category.localeCompare(b.category);
        }
        return a.name.localeCompare(b.name);
    });
}
